// Writes backend/pkg/namewords/incb.go, the Indic_Conjunct_Break tables
// pkg/namewords joins grapheme clusters by (rule GB9c), from the engine's
// own: the src/tables.rs of the unicode-segmentation version the engine's
// Cargo.lock pins, so Foundry's clusters are the engine's.
//
//   node scripts/namewords-incb.mjs ~/.cargo/registry/src/*/unicode-segmentation-<version>/src/tables.rs <version>
import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";

const [tablesPath, version] = process.argv.slice(2);
if (!tablesPath || !version) {
  throw new Error(
    "usage: node scripts/namewords-incb.mjs <unicode-segmentation src/tables.rs> <version>",
  );
}
const src = readFileSync(tablesPath, "utf8");
const unicode = src
  .match(/UNICODE_VERSION: \(u64, u64, u64\) = \((\d+), (\d+), (\d+)\)/)
  .slice(1)
  .join(".");
const pair = String.raw`\('\\u\{([0-9a-f]+)\}',\s*'\\u\{([0-9a-f]+)\}'`;
const ranges = (text, re) =>
  [...text.matchAll(new RegExp(re, "g"))].map((m) => [
    parseInt(m[1], 16),
    parseInt(m[2], 16),
  ]);

const extendBody = src.match(
  /const InCB_Extend_table: &\[\(char, char\)\] = &\[([\s\S]*?)\];/,
)[1];
const extend = ranges(extendBody, pair);
const consonant = ranges(src, pair + String.raw`,\s*GC_InCB_Consonant\)`);
const linkerBody = src.match(
  /pub fn is_incb_linker[\s\S]*?matches!\(c,([\s\S]*?)\)\n/,
)[1];
const linker = [...linkerBody.matchAll(/'\\u\{([0-9A-Fa-f]+)\}'/g)].map((m) => [
  parseInt(m[1], 16),
  parseInt(m[1], 16),
]);

const merge = (rs) =>
  rs
    .sort((a, b) => a[0] - b[0])
    .reduce((out, [lo, hi]) => {
      const last = out.at(-1);
      if (last && lo <= last[1] + 1) last[1] = Math.max(last[1], hi);
      else out.push([lo, hi]);
      return out;
    }, []);
const hex = (n, width) =>
  "0x" + n.toString(16).toUpperCase().padStart(width, "0");
const table = (name, doc, rs) => {
  const merged = merge(rs);
  const r16 = merged.filter(([, hi]) => hi <= 0xffff);
  const r32 = merged.filter(([, hi]) => hi > 0xffff);
  const latin = r16.filter(([, hi]) => hi <= 0xff).length;
  let out = `// ${doc}\nvar ${name} = &unicode.RangeTable{\n`;
  if (r16.length)
    out +=
      "\tR16: []unicode.Range16{\n" +
      r16
        .map(([lo, hi]) => `\t\t{${hex(lo, 4)}, ${hex(hi, 4)}, 1},\n`)
        .join("") +
      "\t},\n";
  if (r32.length)
    out +=
      "\tR32: []unicode.Range32{\n" +
      r32
        .map(([lo, hi]) => `\t\t{${hex(lo, 0)}, ${hex(hi, 0)}, 1},\n`)
        .join("") +
      "\t},\n";
  if (latin) out += `\tLatinOffset: ${latin},\n`;
  return out + "}\n";
};

writeFileSync(
  "backend/pkg/namewords/incb.go",
  `// Code generated by scripts/namewords-incb.mjs. DO NOT EDIT.
// From the engine's unicode-segmentation ${version} (Unicode ${unicode}), src/tables.rs.

package namewords

import "unicode"

${table("incbLinker", "incbLinker is Indic_Conjunct_Break=Linker.", linker)}
${table("incbConsonant", "incbConsonant is Indic_Conjunct_Break=Consonant.", consonant)}
${table("incbExtend", "incbExtend is Indic_Conjunct_Break=Extend.", extend)}`,
);
